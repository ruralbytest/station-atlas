import assert from 'node:assert/strict';
import fs from 'node:fs';
import {visibilityFor} from '../app/visibility.ts';
import {restoreView,viewHash} from '../app/view-url.ts';
import {decodeModelResponse} from '../app/model-download.ts';
import {gzipSync} from 'node:zlib';
const atlas=JSON.parse(fs.readFileSync('public/models/atlas.json','utf8'));
const initial={visible:[...new Set(atlas.parts.map(p=>p.system))],selected:[],assembly:null,isolate:false,explode:0,view:'three-quarter',rotate:false,reset:0},start=Date.UTC(1998,10,20),end=Date.UTC(2011,11,31);
const concept=atlas.concepts.find(c=>c.id==='lab'),part=atlas.parts.find(p=>p.conceptId==='lab');
const state={...initial,visible:[],selected:concept.elements,view:'side',assembly:Date.UTC(2001,1,7)};
assert.equal(visibilityFor({...state,assembly:start})(part,Date.UTC(2001,1,7)),false);
assert.equal(visibilityFor(state)(part,Date.UTC(2001,1,7)),true,'selection overrides system filtering after launch');
assert.equal(visibilityFor({...state,isolate:true,selected:[]})(part,start),false);
assert.deepEqual(restoreView(viewHash(state,atlas),atlas,initial,start,end).state,state);
const invalid=restoreView('#view=invalid&systems=bad&date=2001-02-31&explode=Infinity&element=bad&isolate=1',atlas,initial,start,end).state;
assert.equal(invalid.view,initial.view);assert.equal(invalid.assembly,null);assert.equal(invalid.explode,0);assert.equal(invalid.isolate,false);assert.deepEqual(invalid.visible,[]);
const body=new Uint8Array([1,2,3,4]);
for(const payload of [body,gzipSync(body)])assert.deepEqual(new Uint8Array(await decodeModelResponse(new Response(payload),4,true)),body);
await assert.rejects(()=>decodeModelResponse(new Response(body),5,false),/incomplete/);
await assert.rejects(()=>decodeModelResponse(new Response('',{status:503}),0,false),/could not be loaded/);
console.log('Visibility, URL round-trip/validation, raw/gzip decoding and loading failures passed.');
